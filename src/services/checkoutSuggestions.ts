export const NORMAL_OUT_CHECKOUTS: Record<number, string[]> = (() => {
  const targets: { name: string; value: number; difficulty: number }[] = [];

  // Simples (S1-S20)
  for (let i = 1; i <= 20; i++) {
    targets.push({ name: `S${i}`, value: i, difficulty: 1.0 });
  }

  // Simple Bull (S25)
  targets.push({ name: 'S25', value: 25, difficulty: 3.0 });

  // Doubles (D1-D20)
  for (let i = 1; i <= 20; i++) {
    targets.push({ name: `D${i}`, value: i * 2, difficulty: 4.0 });
  }

  // Triples (T1-T20)
  for (let i = 1; i <= 20; i++) {
    targets.push({ name: `T${i}`, value: i * 3, difficulty: 5.0 });
  }

  // Double Bull (BULL)
  targets.push({ name: 'BULL', value: 50, difficulty: 7.0 });

  function getTargetValue(name: string): number {
    if (name === 'BULL') return 50;
    if (name === 'S25') return 25;
    const num = parseInt(name.substring(1), 10);
    if (name.startsWith('S')) return num;
    if (name.startsWith('D')) return num * 2;
    if (name.startsWith('T')) return num * 3;
    return 0;
  }

  function findBestCheckout(score: number): string[] {
    let bestCombination: string[] = [];
    let minDifficulty = Infinity;
    
    // 1 fléchette
    for (const t1 of targets) {
      if (t1.value === score) {
        const diff = t1.difficulty;
        if (diff < minDifficulty) {
          minDifficulty = diff;
          bestCombination = [t1.name];
        }
      }
    }
    
    // 2 fléchettes
    for (const t1 of targets) {
      for (const t2 of targets) {
        if (t1.value + t2.value === score) {
          const diff = t1.difficulty + t2.difficulty;
          if (diff < minDifficulty) {
            minDifficulty = diff;
            bestCombination = [t1.name, t2.name].sort((a, b) => getTargetValue(b) - getTargetValue(a));
          }
        }
      }
    }
    
    // 3 fléchettes
    for (const t1 of targets) {
      for (const t2 of targets) {
        for (const t3 of targets) {
          if (t1.value + t2.value + t3.value === score) {
            const diff = t1.difficulty + t2.difficulty + t3.difficulty;
            if (diff < minDifficulty) {
              minDifficulty = diff;
              bestCombination = [t1.name, t2.name, t3.name].sort((a, b) => getTargetValue(b) - getTargetValue(a));
            }
          }
        }
      }
    }
    
    return bestCombination;
  }

  const checkouts: Record<number, string[]> = {};
  for (let s = 1; s <= 180; s++) {
    const combo = findBestCheckout(s);
    if (combo.length > 0) {
      checkouts[s] = combo;
    }
  }
  return checkouts;
})()

/**
 * Tables pré-calculées de finitions rapides en 1 et 2 fléchettes pour s'adapter dynamiquement
 * au nombre exact de fléchettes restantes dans la volée (dartsLeft = 1 ou 2).
 */
const SHORT_CHECKOUTS = (() => {
  interface DartOption {
    name: string;
    value: number;
    difficulty: number;
    isDouble: boolean;
  }

  const allDarts: DartOption[] = [];
  // Simples (S1-S20)
  for (let i = 1; i <= 20; i++) {
    allDarts.push({ name: `S${i}`, value: i, difficulty: 1.0, isDouble: false });
  }
  // Simple Bull (S25)
  allDarts.push({ name: 'S25', value: 25, difficulty: 3.0, isDouble: false });

  // Doubles (D1-D20) avec préférence pour les Doubles classiques (D20, D16, D18, D10, D8, D12)
  const preferredDoubles = new Set([20, 16, 18, 10, 8, 12, 4, 2]);
  for (let i = 1; i <= 20; i++) {
    const diff = preferredDoubles.has(i) ? 3.5 : 4.2;
    allDarts.push({ name: `D${i}`, value: i * 2, difficulty: diff, isDouble: true });
  }

  // Triples (T1-T20) avec préférence pour les grands Triples (T20, T19, T18, T17)
  for (let i = 1; i <= 20; i++) {
    const diff = i >= 17 ? 4.8 : 5.2;
    allDarts.push({ name: `T${i}`, value: i * 3, difficulty: diff, isDouble: false });
  }

  // Double Bull (BULL = 50)
  allDarts.push({ name: 'BULL', value: 50, difficulty: 6.5, isDouble: true });

  const double1Dart: Record<number, string[]> = {};
  const double2Darts: Record<number, string[]> = {};
  const normal1Dart: Record<number, string[]> = {};
  const normal2Darts: Record<number, string[]> = {};

  // 1 fléchette
  for (let s = 1; s <= 60; s++) {
    let bestNormal: string[] | null = null;
    let minNormalDiff = Infinity;
    let bestDouble: string[] | null = null;
    let minDoubleDiff = Infinity;

    for (const d1 of allDarts) {
      if (d1.value === s) {
        if (d1.difficulty < minNormalDiff) {
          minNormalDiff = d1.difficulty;
          bestNormal = [d1.name];
        }
        if (d1.isDouble && d1.difficulty < minDoubleDiff) {
          minDoubleDiff = d1.difficulty;
          bestDouble = [d1.name];
        }
      }
    }

    if (bestNormal) normal1Dart[s] = bestNormal;
    if (bestDouble) double1Dart[s] = bestDouble;
  }

  // 2 fléchettes
  for (let s = 2; s <= 120; s++) {
    if (normal1Dart[s]) {
      normal2Darts[s] = normal1Dart[s];
    } else {
      let bestNormal: string[] | null = null;
      let minNormalDiff = Infinity;
      for (const d1 of allDarts) {
        for (const d2 of allDarts) {
          if (d1.value + d2.value === s) {
            const diff = d1.difficulty + d2.difficulty;
            if (diff < minNormalDiff) {
              minNormalDiff = diff;
              bestNormal = d1.value >= d2.value ? [d1.name, d2.name] : [d2.name, d1.name];
            }
          }
        }
      }
      if (bestNormal) normal2Darts[s] = bestNormal;
    }

    if (double1Dart[s]) {
      double2Darts[s] = double1Dart[s];
    } else {
      let bestDouble: string[] | null = null;
      let minDoubleDiff = Infinity;
      for (const d1 of allDarts) {
        for (const d2 of allDarts) {
          if (d2.isDouble && d1.value + d2.value === s) {
            const diff = d1.difficulty + d2.difficulty;
            if (diff < minDoubleDiff) {
              minDoubleDiff = diff;
              bestDouble = [d1.name, d2.name];
            }
          }
        }
      }
      if (bestDouble) double2Darts[s] = bestDouble;
    }
  }

  return { double1Dart, double2Darts, normal1Dart, normal2Darts };
})();

/**
 * Récupère la suggestion de finition (checkout) pour un score donné, un mode de sortie et le nombre de fléchettes restantes.
 * @param score Le score restant du joueur.
 * @param doubleOut Si true, utilise les règles de Double Out.
 * @param dartsLeft Nombre de fléchettes restantes dans la volée courante (1, 2 ou 3). Par défaut 3.
 * @returns Un tableau de chaînes représentant les fléchettes à viser, ou null si aucune finition n'est possible avec ces fléchettes.
 */
export function getCheckoutSuggestion(score: number, doubleOut: boolean, dartsLeft: number = 3): string[] | null {
  if (score <= 0 || score > 180 || dartsLeft <= 0) return null;
  if (doubleOut && score === 1) return null;

  const suggestions = doubleOut ? DOUBLE_OUT_CHECKOUTS : NORMAL_OUT_CHECKOUTS;
  const standardCombo = suggestions[score] || null;

  // Si la combinaison standard tient dans le nombre de fléchettes en main, on la privilégie
  if (standardCombo && standardCombo.length <= dartsLeft) {
    return standardCombo;
  }

  // Sinon, on cherche une finition réalisable en 1 ou 2 fléchettes (ex: 110 -> T20 + BULL avec 2 fléchettes)
  if (dartsLeft === 1) {
    return (doubleOut ? SHORT_CHECKOUTS.double1Dart[score] : SHORT_CHECKOUTS.normal1Dart[score]) || null;
  }

  if (dartsLeft === 2) {
    return (doubleOut ? SHORT_CHECKOUTS.double2Darts[score] : SHORT_CHECKOUTS.normal2Darts[score]) || null;
  }

  return standardCombo;
}
